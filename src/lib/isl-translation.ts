import { translationProvider, normalize, type TranslationProvider } from './translation';
import { ISL_REFERENCE, ISL_REFERENCE_PHRASES } from './isl-reference';
import type { Phrase, Sign, Translation } from './schemas';
import { findDatasetGloss } from './isl-dataset';
import {
  IslModelError,
  islMotionSchema,
  researchMotionSchema,
  type IslMotionProvider,
} from './isl-motion-schema';

type Options = {
  allowReferencePreview?: boolean;
  allowUnreviewedModel?: boolean;
  signal?: AbortSignal;
};

// Reviewed mappings and validated model motion have separate trust gates.
// The reference path matches whole utterances, never English word substitution.
export class LocalIslProvider {
  id = 'isl-motion-router-v2';
  constructor(
    private reviewedProvider: TranslationProvider = translationProvider,
    private motionProvider?: IslMotionProvider,
  ) {}
  async translate(
    text: string,
    language: string,
    phrases: Phrase[],
    signs: Sign[],
    options: Options = {},
  ): Promise<Translation> {
    text = text.trim();
    const strict = await this.reviewedProvider.translate(text, language, phrases, signs);
    const datasetMatch = language === 'en' ? findDatasetGloss(text) : undefined;
    const base = {
      ...strict,
      datasetMatch,
      outputMode: 'isl' as const,
      targetLanguage: 'ISL' as const,
      requestedLanguage: 'ISL' as const,
    };
    if (strict.playback === 'ready') return { ...base, rendering: 'reviewed-isl' };
    if (
      language === 'en' &&
      this.motionProvider &&
      !(this.motionProvider.scope === 'local-research' && !options.allowUnreviewedModel)
    ) {
      try {
        const output = await this.motionProvider.generate(text, language, options.signal);
        if (output !== null) {
          const parsed = (
            this.motionProvider.scope === 'local-research' ? researchMotionSchema : islMotionSchema
          ).safeParse(output);
          if (!parsed.success || parsed.data.sourceText !== text)
            throw new IslModelError(
              'model-output-invalid',
              'The ISL model returned incompatible or incomplete motion. Nothing was played.',
            );
          const motion = parsed.data;
          if (motion.review.status === 'unreviewed' && !options.allowUnreviewedModel)
            return {
              ...base,
              status: 'supported',
              assetAvailability: 'available',
              phrase: null,
              match: null,
              sequence: [],
              playback: 'review-required',
              rendering: 'none',
              blockReason: 'model-review-required',
              message:
                'The model returned unreviewed ISL motion. Enable unreviewed model output to inspect it; this is not a certified translation.',
            };
          return {
            ...base,
            status: 'supported',
            playback: 'ready',
            assetAvailability: 'available',
            phrase: null,
            match: null,
            rendering: 'isl-model-motion',
            generatedMotion: motion,
            sequence: motion.segments.map((segment, i) => ({
              id: `isl-generated-${i}`,
              clip: `isl-generated-${i}`,
              asset: null,
              label: `Segment ${i + 1}`,
              gloss: segment.gloss,
              duration: segment.clip.duration,
              transition: 0,
              review: motion.review.status,
              available: true,
              fallback: 'rest',
              source: motion.model.source,
              license: motion.model.license,
              provenance: motion.model.attribution,
              token: {
                start: segment.start,
                end: segment.end,
                wordIndex: i,
                wordStart: segment.start,
                wordEnd: segment.end,
                kind: 'phrase',
              },
            })),
            provenance: motion.model.attribution,
            warnings: [
              'Model provenance and review are reported by the configured provider, not independently certified by SignBridge. The procedural avatar is a visualization rig, not a validated interpreter.',
              ...motion.limitations,
            ],
            message: `ISL motion generated by ${motion.model.id} (${motion.model.version}). ${motion.review.status === 'reviewed' ? 'The provider reports an expert review; consult its evidence.' : 'Expert review is pending. Do not rely on this output for interpretation.'}`,
          };
        }
      } catch (error) {
        if (options.signal?.aborted) throw error;
        if (this.motionProvider.scope === 'local-research' && options.allowReferencePreview) {
          const reference = await new LocalIslProvider(this.reviewedProvider).translate(
            text,
            language,
            phrases,
            signs,
            options,
          );
          if (reference.playback === 'ready') return reference;
        }
        const issue =
          error instanceof IslModelError
            ? error
            : new IslModelError(
                'model-unavailable',
                'ISL generation failed. No substitute motion was generated.',
              );
        return {
          ...base,
          status: 'unsupported',
          sequence: [],
          playback: 'unsupported',
          assetAvailability: 'missing',
          rendering: 'none',
          blockReason: issue.code,
          unsupportedWords: issue.unsupportedWords.length ? issue.unsupportedWords : undefined,
          message: issue.message,
        };
      }
    }
    if (language === 'en' && options.allowReferencePreview) {
      const exact = ISL_REFERENCE_PHRASES.find((p) =>
        [p.text, ...p.aliases].some((v) => normalize(v) === normalize(text)),
      );
      const chunks = exact
        ? [{ text, start: 0, end: text.length }]
        : [...text.matchAll(/[^.!?;\n]+[.!?;\n]*/g)]
            .map((m) => ({
              text: m[0].trim(),
              start: m.index + m[0].length - m[0].trimStart().length,
              end: m.index + m[0].trimEnd().length,
            }))
            .filter((c) => c.text.length);
      const matches = chunks.map((chunk) => {
        const reference = ISL_REFERENCE_PHRASES.find((p) =>
          [p.text, ...p.aliases].some((v) => normalize(v) === normalize(chunk.text)),
        );
        const phrase =
          reference &&
          phrases.find(
            (p) =>
              p.id === reference.id &&
              p.review === 'unreviewed' &&
              p.source === ISL_REFERENCE &&
              p.signIds.join() === reference.signIds.join(),
          );
        const motion =
          phrase &&
          signs.find(
            (s) =>
              s.id === reference!.signIds[0] &&
              s.clip === s.id &&
              s.available &&
              s.review === 'unreviewed' &&
              s.source === ISL_REFERENCE &&
              !s.asset,
          );
        return { ...chunk, phrase, motion };
      });
      if (matches.length && matches.every((m) => m.phrase && m.motion)) {
        return {
          ...base,
          status: 'supported',
          playback: 'ready',
          assetAvailability: 'available',
          rendering: 'isl-reference-preview',
          phrase: matches.length === 1 ? matches[0].phrase! : null,
          match:
            matches.length === 1
              ? normalize(matches[0].phrase!.text) === normalize(text)
                ? 'exact'
                : 'alias'
              : null,
          phraseMatches: matches.map((m) => ({
            id: m.phrase!.id,
            text: m.phrase!.text,
            start: m.start,
            end: m.end,
          })),
          sequence: matches.map((m, i) => ({
            ...m.motion!,
            token: {
              start: m.start,
              end: m.end,
              wordIndex: i,
              wordStart: m.start,
              wordEnd: m.end,
              kind: 'phrase',
            },
          })),
          provenance: ISL_REFERENCE,
          message:
            'Original ISL reference previews for complete supported phrases. These approximations have not been reviewed by an ISL expert; facial grammar is not reconstructed.',
        };
      }
    }
    return {
      ...base,
      rendering: 'none',
      ...(strict.status === 'unsupported'
        ? {
            blockReason: 'model-not-configured' as const,
            message:
              'No English-to-ISL motion model is installed for this input. The seven reference previews do not translate arbitrary sentences. No text was discarded and no ASL spelling or invented ISL gestures were substituted.',
          }
        : {}),
    };
  }
}
export const localIslProvider = new LocalIslProvider();
